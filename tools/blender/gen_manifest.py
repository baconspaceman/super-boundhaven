"""Generate packages/art/src/blender/manifest.ts from the pixelizer's JSON (bg_manifest.json + sprites.json)."""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ASSETS = os.path.join(HERE, "..", "..", "packages", "art", "assets", "blender")
OUT = os.path.join(HERE, "..", "..", "packages", "art", "src", "blender", "manifest.ts")

bg = json.load(open(os.path.join(ASSETS, "bg_manifest.json")))
sp = json.load(open(os.path.join(ASSETS, "sprites.json")))

L = []
L.append("// GENERATED by tools/blender/gen_manifest.py -- do not edit. Run: npm run build:blender -w @sbh/art")
L.append("// All file paths are relative to packages/art/assets/blender/.")
L.append("")
L.append("export type BlenderTod = 'dawn' | 'day' | 'sunset' | 'night';")
L.append("")
L.append("export interface BlenderLayer {")
L.append("  name: string;")
L.append("  file: string;")
L.append("  /** horizontal scroll multiplier (0 = fixed sky, ~0.8 = near) */")
L.append("  parallax: number;")
L.append("  /** screen y (px, from top of the 224px frame) where the image's top row is drawn */")
L.append("  y: number;")
L.append("  tileX: boolean;")
L.append("  width: number;")
L.append("  height: number;")
L.append("}")
L.append("")
L.append("export const BLENDER_BACKGROUNDS: Record<BlenderTod, BlenderLayer[]> = {")
for t in ["dawn", "day", "sunset", "night"]:
    L.append("  %s: [" % t)
    for r in bg[t]:
        L.append("    { name: '%s', file: '%s', parallax: %s, y: %d, tileX: %s, width: %d, height: %d }," % (r["name"], r["file"], r["parallax"], r["y"], str(r["tileX"]).lower(), r["width"], r["height"]))
    L.append("  ],")
L.append("};")
L.append("")
L.append("export interface BlenderSpriteMeta {")
L.append("  /** atlas frame names, in animation order */")
L.append("  frames: string[];")
L.append("  /** ground/pivot point inside each (identically cropped) frame, px from top-left */")
L.append("  anchor: [number, number];")
L.append("  /** 0 = static */")
L.append("  fps: number;")
L.append("  size: [number, number];")
L.append("}")
L.append("")
L.append("export const BLENDER_SPRITES = {")
L.append("  image: '%s'," % sp["image"])
L.append("  json: 'sprites.json',")
L.append("  width: %d," % sp["w"])
L.append("  height: %d," % sp["h"])
L.append("  atlas: {")
for n, r in sp["frames"].items():
    L.append("    %s: { x: %d, y: %d, w: %d, h: %d }," % (n, r["x"], r["y"], r["w"], r["h"]))
L.append("  } as Record<string, { x: number; y: number; w: number; h: number }>,")
L.append("  sprites: {")
for n, r in sp["sprites"].items():
    L.append("    %s: { frames: [%s], anchor: [%d, %d], fps: %d, size: [%d, %d] }," % (n, ", ".join("'%s'" % f for f in r["frames"]), r["anchor"][0], r["anchor"][1], r["fps"], r["size"][0], r["size"][1]))
L.append("  } as Record<string, BlenderSpriteMeta>,")
L.append("};")
L.append("")
open(OUT, "w", encoding="utf8").write("\n".join(L))
print("manifest.ts written")
